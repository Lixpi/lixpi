import {
    mkdirSync,
    readFileSync,
    writeFileSync,
} from 'node:fs'
import { dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import {
    gentelellaStylesheetRules,
    themeStylesheetRoles,
    themeNames,
    getThemeStylesheet,
    type ApplicationTheme,
} from '../src/index.ts'

type Properties = Readonly<Record<string, string>>

const header = '// Generated by @lixpi/themes tooling/generate.ts from TypeScript theme definitions. Do not edit.\n'
const check = process.argv.includes('--check')

const emit = (
    relativePath: string,
    content: string,
): void => {
    const path = fileURLToPath(
        new URL(relativePath, import.meta.url),
    )
    const expected = header + content
    let existing: string | undefined

    try {
        existing = readFileSync(path, 'utf8')
    } catch (error) {
        if ((error as NodeJS.ErrnoException).code !== 'ENOENT')
            throw error
    }

    if (existing === expected)
        return

    if (check) {
        process.stderr.write(`Run themes:generate to update ${relativePath}\n`)
        process.exitCode = 1

        return
    }

    mkdirSync(
        dirname(path),
        { recursive: true },
    )
    writeFileSync(path, expected)
}

const sassMap = (
    values: Properties,
    quoteValues: boolean,
    indentation = '    ',
    closingIndentation = '',
): string => {
    const entries = Object.entries(values)
    const lines = entries.map(([key, value], index) => {
        const sassValue = quoteValues
            ? JSON.stringify(value)
            : value.replace(/#[\da-fA-F]{3,8}\b/g, color => color.toLowerCase())

        return `${indentation}${JSON.stringify(key)}: ${sassValue}${index === entries.length - 1 ? '' : ','}`
    })

    return [`${closingIndentation}(`, ...lines, `${closingIndentation})`].join('\n')
}

const declarations = (
    properties: Properties,
    indentation: string,
): string =>
    Object.entries(properties).map(([name, value]) => `${indentation}${name}: ${value.replace(/#[\da-fA-F]{3,8}\b/g, color => color.toLowerCase())};`)
        .join('\n')

const emitTheme = (
    theme: ApplicationTheme,
    selector: string,
    palette: Properties,
    stylesheetRoles: Properties,
    paletteVariables?: Properties,
): void => {
    const fallbacks = themeStylesheetRoles(theme)
    const aliases = Object.fromEntries(
        Object.entries(stylesheetRoles).filter(([name, value]) => value !== fallbacks[name as keyof typeof fallbacks]),
    )
    const paletteStyles = [
        '@use "sass:map";',
        `$palette: ${sassMap(palette, false)};`,
        `$roles: ${sassMap(fallbacks, true)};`,
        `$value-roles: ${sassMap(
            Object.fromEntries(
                Object.entries(fallbacks).filter(
                    ([, value]) => /^(?:-?\d+(?:\.\d+)?(?:px|rem|em|%|deg|ms|s)?|#[\da-fA-F]{3,8}|(?:rgb|rgba|hsl|hsla)\([^)]*\))$/.test(value),
                ),
            ),
            false,
        )};`,
        [
            '$stylesheet-roles: map.merge(',
            '    $roles,',
            sassMap(
                aliases,
                true,
                '        ',
                '    ',
            ),
            ');',
        ].join('\n'),
    ]

    if (paletteVariables)
        paletteStyles.push(`:root, [data-color-theme="${theme.name}"] {\n${declarations(paletteVariables, '    ')}\n}`)

    emit(`../dist/scss/${theme.name}/palette.scss`, `${paletteStyles.join('\n\n')}\n`)
    emit(
        `../dist/scss/${theme.name}/theme.scss`,
        [
            '@use "../../../src/projections/scope.scss";',
            '@use "./palette";',
            '',
            `$name: "${theme.name}";`,
            `$selector: ${JSON.stringify(selector)};`,
            '',
            `@include scope.apply($selector, $name, ${theme.colorScheme}, palette.$stylesheet-roles);`,
            '',
        ].join('\n'),
    )
}

for (const name of themeNames) {
    const stylesheet = getThemeStylesheet(name)
    emitTheme(
        stylesheet.theme,
        stylesheet.selector,
        stylesheet.palette,
        stylesheet.roles,
        stylesheet.paletteProperties,
    )
}

emit('../dist/scss/themes.scss', `${themeNames.map((name, index) => `@use "./${name}/theme" as theme${index};`).join('\n')}\n`)

const adapter = Object.entries(
    gentelellaStylesheetRules(),
).map(([selector, properties]) => {
    if (selector === '&')
        return declarations(properties, '        ')

    return `        ${selector.replaceAll('& ', '')} {\n${declarations(properties, '            ')}\n        }`
})
emit('../dist/scss/adapters/gentelella.scss', `@mixin apply($selector) {\n    #{$selector} {\n${adapter.join('\n\n')}\n    }\n}\n`)
